-- 1. Tabla de Usuarios / Alumnos
CREATE TABLE users (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name VARCHAR2(100) NOT NULL,
    email VARCHAR2(100) UNIQUE NOT NULL,
    password_hash VARCHAR2(255) NOT NULL,
    role VARCHAR2(20) NOT NULL CHECK (role IN ('ROLE_ADMIN', 'ROLE_STUDENT')),
    credits_balance NUMBER(10, 0) DEFAULT 0 NOT NULL CHECK (credits_balance >= 0),
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL
);

-- 2. Tabla de Clases de Inglés
CREATE TABLE courses (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title VARCHAR2(100) NOT NULL,
    level_code VARCHAR2(10) NOT NULL,
    credit_cost NUMBER(5, 0) NOT NULL CHECK (credit_cost > 0),
    max_capacity NUMBER(4, 0) NOT NULL CHECK (max_capacity > 0),
    enrolled_count NUMBER(4, 0) DEFAULT 0 NOT NULL CHECK (enrolled_count >= 0),
    CONSTRAINT chk_capacity CHECK (enrolled_count <= max_capacity)
);

-- 3. Tabla de Inscripciones (Relación Alumno - Clase)
CREATE TABLE enrollments (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id NUMBER NOT NULL,
    course_id NUMBER NOT NULL,
    enrolled_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT fk_enroll_user FOREIGN KEY (user_id) REFERENCES users(id),
    CONSTRAINT fk_enroll_course FOREIGN KEY (course_id) REFERENCES courses(id),
    CONSTRAINT uq_user_course UNIQUE (user_id, course_id)
);

-- 4. Tabla de Auditoría de Créditos (Ledger)
CREATE TABLE credit_transactions (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id NUMBER NOT NULL,
    amount NUMBER(10, 0) NOT NULL,
    transaction_type VARCHAR2(20) NOT NULL CHECK (transaction_type IN ('ASSIGNMENT', 'ENROLLMENT', 'REFUND')),
    description VARCHAR2(255) NOT NULL,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT fk_tx_user FOREIGN KEY (user_id) REFERENCES users(id)
);

